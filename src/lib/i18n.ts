export function normalizeLanguage(value?: string | null): AppLanguage {
  if (!value) return defaultLanguage
  const normalized = value.toLowerCase()
  if (normalized.startsWith('zh')) return 'zh-CN'
  if (normalized.startsWith('ja')) return 'ja'
  if (normalized.startsWith('fr')) return 'fr'
  if (normalized.startsWith('en')) return 'en'
  return appLanguages.includes(value as AppLanguage) ? (value as AppLanguage) : defaultLanguage
}

export function appLanguageToLocale(language: AppLanguage): string {
  return (
    {
      en: 'en-US',
      'zh-CN': 'zh-CN',
      ja: 'ja-JP',
      fr: 'fr-FR',
    } satisfies Record<AppLanguage, string>
  )[language]
}

