function mergeTranslations(
  base: Partial<Record<TranslationKey, string>>,
  extra: Partial<Record<TranslationKey, string>> = {},
): Record<TranslationKey, string> {
  return { ...en, ...base, ...extra }
}

const translations = {
  en,
  'zh-CN': mergeTranslations(zh, zhExtra),
  ja: mergeTranslations(ja, jaExtra),
  fr: mergeTranslations(fr, frExtra),
} satisfies Record<AppLanguage, Record<TranslationKey, string>>

export function translate(
  language: AppLanguage,
  key: TranslationKey,
  values: TranslationValues = {},
): string {
  const template = translations[language][key] ?? en[key]
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, name: string) =>
    String(values[name] ?? `{${name}}`),
  )
}

export function formatRelativeForLanguage(
  value: string | undefined,
  language: AppLanguage,
): string {
  if (!value) return translate(language, 'time.never')
  const date = new Date(value)
  const diffMs = Date.now() - date.getTime()
  if (Number.isNaN(diffMs)) return translate(language, 'common.unknown')

  const minutes = Math.max(0, Math.floor(diffMs / 60_000))
  if (minutes < 1) return translate(language, 'time.justNow')

  const formatter = new Intl.RelativeTimeFormat(appLanguageToLocale(language), {
    numeric: 'auto',
  })
  if (minutes < 60) return formatter.format(-minutes, 'minute')

  const hours = Math.floor(minutes / 60)
  if (hours < 24) return formatter.format(-hours, 'hour')

  const days = Math.floor(hours / 24)
  if (days < 7) return formatter.format(-days, 'day')

  return date.toLocaleDateString(appLanguageToLocale(language))
}
